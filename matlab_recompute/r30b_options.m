function o=r30b_options(user)
% Explicit units: mm,s,N,Nmm. Candidate coefficients, not a Dietz fit.
o=struct('faces',[17 1;17 2],'ns',400,'nz',800,'order',2,...
 'window_s',[],'windowCenter_s',15,'windowSearchStep_s',.002,...
 'dt_s',.0001,'substeps',2,'historyDt_s',.00005,'historyBlock_s',.002,...
 'normalDepthLimit_mm',1,'heightTolerance_mm',1e-10,'forceStripWidth_mm',.1,...
 'referenceOutward',[1 0 0],'outputDir','r30_dual_recomputed',...
 'resume',true,'checkpointEvery_s',30,'progressEvery_s',5,...
 'saveFrames',true,'frameStride',1,'saveStripPolygons',false,'plot',true,'visible',false,...
 'coefficients',struct('Kn',1000,'m',.6,'p',.4,'mu',.45,'h_ref',1,'l_ref',1,...
  'background_pressure',0,'calibrated',false));
if nargin<1,user=struct();end
names=fieldnames(user);for j=1:numel(names)
 assert(isfield(o,names{j}),'R30B:Options','Unknown option: %s',names{j});
 if strcmp(names{j},'coefficients')
  nn=fieldnames(user.coefficients);for k=1:numel(nn)
   assert(isfield(o.coefficients,nn{k}),'R30B:Coefficient','Unknown coefficient');o.coefficients.(nn{k})=user.coefficients.(nn{k});
  end
 else,o.(names{j})=user.(names{j});end
end
assert(size(o.faces,2)==2&&~isempty(o.faces)&&size(unique(o.faces,'rows'),1)==size(o.faces,1),...
 'R30B:Faces','Supply distinct [tooth side] pairs');
assert(all(o.faces(:,1)>=1&o.faces(:,1)<=30&mod(o.faces(:,1),1)==0)&&all(ismember(o.faces(:,2),[1 2])),...
 'R30B:Faces','Supported labels: tooth1..30, side1/2');
assert(all([o.ns o.nz o.order o.substeps o.frameStride]>=1)&&...
 all(mod([o.ns o.nz o.order o.substeps o.frameStride],1)==0),'R30B:Grid','Grid/order/substeps/stride must be positive integers');
assert(all(isfinite([o.dt_s o.historyDt_s o.forceStripWidth_mm o.normalDepthLimit_mm]))&&...
 min([o.dt_s o.historyDt_s o.forceStripWidth_mm o.normalDepthLimit_mm])>0&&o.normalDepthLimit_mm<=1,...
 'R30B:Resolution','Invalid increments or supported normal-depth limit');
assert(o.heightTolerance_mm>=0&&o.heightTolerance_mm<1e-6,'R30B:Tolerance','Invalid material update tolerance');
assert(o.progressEvery_s>0&&o.checkpointEvery_s>0&&o.historyBlock_s>0&&o.windowSearchStep_s>0,...
 'R30B:Options','Progress/checkpoint/block/search intervals must be positive');
n=o.referenceOutward(:)';assert(numel(n)==3&&all(isfinite(n))&&norm(n)>1e-12,'R30B:Reference','Reference outward direction must be nonzero');
o.referenceOutward=n/norm(n);
f=o.coefficients;
assert(all(isfinite([f.Kn f.m f.p f.mu f.h_ref f.l_ref f.background_pressure]))&&...
 f.Kn>=0&&f.m>0&&f.p>=0&&f.mu>=0&&f.h_ref>0&&f.l_ref>0&&f.background_pressure>=0,...
 'R30B:Coefficient','Invalid candidate force coefficients');
assert(f.background_pressure==0,'R30B:ContactScope','This version models active removal only; a rubbing-contact background term requires an additional full-contact model');
end
