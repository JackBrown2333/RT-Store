function C=r30b_compare_runs(coarseFile,fineFile,outputFile)
% Finite spatial/history/time refinement, with physical time-bin matching.
% Fine vectors are averaged over each coarse interval BEFORE taking norms.
if nargin<3,outputFile='';end
a=load(coarseFile,'R30B');b=load(fineFile,'R30B');a=a.R30B;b=b.R30B;
assert(isequaln(a.parameters,b.parameters)&&isequal(a.faces,b.faces)&&...
 isequaln(a.forceCoefficients,b.forceCoefficients)&&max(abs(a.window_s-b.window_s))<1e-10,...
 'R30B:Compare','Use identical geometry, faces, coefficients and explicit physical windows');
ratio=a.options.dt_s/b.options.dt_s;m=round(ratio);
assert(m>=1&&abs(m-ratio)<1e-9&&numel(b.poses)==numel(a.poses)*m,...
 'R30B:Compare','Fine intervals must partition each coarse interval exactly');
F=vertcat(a.poses.force_N);N=vertcat(a.poses.normalVector_N);fineF=zeros(size(F));fineN=fineF;fineV=zeros(numel(a.poses),1);
for k=1:numel(a.poses)
 ids=(k-1)*m+(1:m);assert(abs(b.poses(ids(end)).t_s-a.poses(k).t_s)<1e-10);
 dt=[b.poses(ids).dt_s]';fineF(k,:)=sum(vertcat(b.poses(ids).force_N).*dt,1)/a.poses(k).dt_s;
 fineN(k,:)=sum(vertcat(b.poses(ids).normalVector_N).*dt,1)/a.poses(k).dt_s;fineV(k)=sum([b.poses(ids).dV_mm3]);
end
coarseV=[a.poses.dV_mm3]';normal=sqrt(sum(N.^2,2));fineNormal=sqrt(sum(fineN.^2,2));
C=struct('status','comparison_only_no_automatic_convergence_claim','faces',a.faces,'window_s',a.window_s,...
 'coarse_dt_s',a.options.dt_s,'fine_dt_s',b.options.dt_s,...
 'totalVolumeDifference_mm3',sum(coarseV)-sum(fineV),...
 'maxCommonBinVolumeDifference_mm3',max(abs(coarseV-fineV)),...
 'maxVolumeDifference_overFinePeak',max(abs(coarseV-fineV))/max(max(fineV),realmin),...
 'maxForceVectorDifference_N',max(sqrt(sum((F-fineF).^2,2))),...
 'maxNormalVectorDifference_N',max(sqrt(sum((N-fineN).^2,2))),...
 'maxPureNormalNormDifference_overFinePeak',max(abs(normal-fineNormal))/max(max(fineNormal),realmin),...
 'note','This is a finite comparison of common-bin volume and time-averaged vectors, not experimental validation.');
if ~isempty(outputFile),fid=fopen(outputFile,'w','n','UTF-8');assert(fid>0);fprintf(fid,'%s',jsonencode(C));fclose(fid);end
disp(C);
end
